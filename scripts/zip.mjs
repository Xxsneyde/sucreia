// Escribe un .zip (deflate) con todos los archivos de una carpeta, sin dependencias: solo zlib de
// Node. Las rutas dentro del zip usan «/» y parten de la carpeta (server.mjs, public/…), que es
// la forma que espera Hostinger al subir la aplicación.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { crc32, deflateRawSync } from 'node:zlib';

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}

/** Fecha y hora en el formato de MS-DOS que usa el zip. */
function dosTime(date) {
  return {
    time: (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2),
    date: ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate(),
  };
}

export function zipFolder(dir, outFile) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  const list = files(dir).sort();
  for (const path of list) {
    const name = Buffer.from(relative(dir, path).split(sep).join('/'), 'utf8');
    const data = readFileSync(path);
    const packed = deflateRawSync(data, { level: 9 });
    // Si comprimir no ayuda (imágenes), se guarda tal cual.
    const stored = packed.length >= data.length;
    const body = stored ? data : packed;
    const { time, date } = dosTime(statSync(path).mtime);
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // versión necesaria
    local.writeUInt16LE(0x0800, 6); // nombres en UTF-8
    local.writeUInt16LE(stored ? 0 : 8, 8);
    local.writeUInt16LE(time, 10);
    local.writeUInt16LE(date, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, name, body);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(stored ? 0 : 8, 10);
    central.writeUInt16LE(time, 12);
    central.writeUInt16LE(date, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(body.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += local.length + name.length + body.length;
  }
  const centralSize = centrals.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(list.length, 8);
  end.writeUInt16LE(list.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  if (list.length > 0xffff || offset > 0xffffffff)
    throw new Error('El paquete es demasiado grande para un zip sin ZIP64.');
  writeFileSync(outFile, Buffer.concat([...locals, ...centrals, end]));
  return { files: list.length, bytes: offset + centralSize + end.length };
}
